export function t(lang: Lang, key: keyof typeof dictionary.en, vars?: Record<string, string>) {
  let value: string = dictionary[lang][key] || dictionary.en[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      value = value.replace(`{${k}}`, v);
    }
  }
  return value;
}

export function periodLabel(lang: Lang, hour?: number) {
  const h = hour ?? 9;
  const key = h < 12 ? "morning" : h < 17 ? "afternoon" : "evening";
  return t(lang, key);
}
